"""Pinned LTX 2.5 assets, explicit inference plan and generated-audio acceptance."""
from ui_strings import source as ui_text
import json
import math
import os
from pathlib import Path

LTX_ID = 'ltx25-distilled'
MANIFEST = Path(__file__).resolve().parents[2]/'config/ltx25-assets.json'
ASSETS = json.loads(MANIFEST.read_text(encoding='utf-8'))['files']
SIGMAS = [1.0,.99375,.9875,.98125,.975,.909375,.725,.421875,0.0]
REFINE_SIGMAS = [.85,.725,.4219,0.0]


def model_root(h3_models):
    return Path(os.environ.get('VISUALFORGE_LTX_MODELS',Path(h3_models).parent/'LTX25')).resolve()


def engine_missing(runtime,h3_models):
    runtime=Path(runtime);models=model_root(h3_models)
    required = [runtime/p for p in ('python/python.exe','ffmpeg/bin/ffmpeg.exe','ffmpeg/bin/ffprobe.exe',
        'vendor/ComfyUI/comfy_extras/nodes_lt.py','vendor/ComfyUI/comfy_extras/nodes_lt_audio.py',
        'vendor/ComfyUI/comfy_extras/nodes_lt_upsampler.py','vendor/ComfyUI/comfy_extras/nodes_hunyuan.py')]
    missing = [str(p) for p in required if not p.is_file()]
    for entry in ASSETS:
        path=models/entry['path']
        if not path.is_file() or path.stat().st_size != entry['bytes']:
            missing.append(str(path))
    return missing


def inference_plan(row):
    two_stages=row['quality']=='standard'
    return dict(base_width=row['width']//2 if two_stages else row['width'],
        base_height=row['height']//2 if two_stages else row['height'],width=row['width'],height=row['height'],
        frames=row['frames'],fps=row['fps'],seed=row['seed'],mode=row['mode'],sampler='euler_ancestral',refine_seed=42+int(row.get('_continuation_index',0)),
        sigmas=list(SIGMAS),refine_sigmas=list(REFINE_SIGMAS) if two_stages else [],video_cfg=1.0,audio_cfg=1.0,
        video_vae='ltx-2.5-video-vae-bf16.safetensors' if two_stages else 'ltx-2.5-video-vae-conv-bf16.safetensors',
        transformer='ltx-2.5-22b-distilled-transformer-comfy-int8-convrot.safetensors',
        text_encoder='gemma4-12b-with-proj-ltx-2.5-comfy-int8-convrot.safetensors',
        audio_vae='ltx-2.5-audio-vae-bf16.safetensors',
        upsampler='ltx-2.5-latent-spatial-upscaler-x2-bf16-1.0.safetensors',
        source='Lightricks/LTX-2.5',revision='49b093a39c19169a8a81721dcc541e07e945232f',
        audio_origin='generated by LTX 2.5',encoder_isolation='owned child process; CPU conditioning; weights_only reload',offload='native ComfyUI RAM offload, reserve 2 GiB')


def validate_audio(streams,duration):
    audio=next((s for s in streams if s.get('codec_type')=='audio'),None)
    if not audio:
        raise ValueError(ui_text('video.validate_audio_ltx_2_5_did_not_save'))
    try:
        actual=float(audio['duration'])
        valid=math.isfinite(actual) and abs(actual-duration)<=.2 and int(audio['channels'])==2 and int(audio['sample_rate'])==48000
    except (KeyError,ValueError,TypeError,OverflowError):
        valid=False
    if not valid:
        raise ValueError(ui_text('video.validate_audio_ltx_2_5_does_not_match'))
