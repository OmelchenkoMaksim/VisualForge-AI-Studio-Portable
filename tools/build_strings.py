"""Validate section catalogs and build the synchronous, offline browser bundle."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TOKENS = re.compile(r'\{\d+\}|%(?:\d+\$)?[-+#0]*(?:\d+)?(?:\.\d+)?[sdifg]|%%')
KEY = re.compile(r'[a-z]+\.[a-z][a-z0-9]*(?:_[a-z0-9]+){2,}\Z')


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('Duplicate JSON field: ' + key)
        result[key] = value
    return result


def catalogs(root=ROOT):
    result = {}
    for path in sorted((root / 'App/strings').glob('*.json')):
        if not path.stem.endswith('-strings'):
            raise ValueError('Translation catalog filename must end with -strings.json: ' + path.name)
        entries = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object)
        # Catalog filenames describe their role; resource namespaces stay stable across renames.
        section = path.stem.removesuffix('-strings')
        for key, value in entries.items():
            if not KEY.fullmatch(key) or '.msg_' in key or not key.startswith(section + '.') or key in result:
                raise ValueError('Invalid or duplicate translation key: ' + key)
            if set(value) != {'ru', 'en'} or not all(isinstance(s, str) and s for s in value.values()):
                raise ValueError('Both languages are required: ' + key)
            if Counter(TOKENS.findall(value['ru'])) != Counter(TOKENS.findall(value['en'])):
                raise ValueError('Translation placeholders differ: ' + key)
            result[key] = value
    if not result:
        raise ValueError('No string catalogs found')
    return result


def bundle(root=ROOT):
    data = json.dumps(catalogs(root), ensure_ascii=False, separators=(',', ':'))
    # Escape script delimiters even though the bundle is served as an external CSP-approved script.
    data = data.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    # Catalog values can mention SQL; they are UI text, with no database connection to configure.
    return ('/* Generated by tools/build_strings.py; edit App/strings/*.json. */\n'
            '// noinspection SqlNoDataSourceInspection\n'
            'globalThis.VisualForgeStrings = ' + data + ';\n').encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'App/frontend/interface-strings.js'
    expected = bundle()
    if args.check:
        if not path.is_file() or path.read_bytes() != expected:
            raise SystemExit('interface-strings.js is stale; run python tools/build_strings.py')
    else:
        path.write_bytes(expected)
    print('String catalogs valid:', len(catalogs()), 'keys')


if __name__ == '__main__':
    main()
